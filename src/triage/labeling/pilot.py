"""Compare teacher candidates on the same val tickets -> docs/reports/pilot.md (ADR-005).

Agreement with the dataset's (noisy) labels is only a sanity check: ADR-010 explains why it is
low. The side-by-side tickets at the end are what a person actually judges on.
"""

import itertools
import json
import logging
import statistics
from pathlib import Path
from typing import Any

from triage import paths
from triage.errors import UserError
from triage.evals.metrics import accuracy, class_scores, macro_f1
from triage.io import Row, read_jsonl
from triage.settings import load_endpoint

log = logging.getLogger(__name__)

N_FULL = 3296  # tickets in test + val + train (docs/reports/splits.md)
N_REVIEW = 20


def rows_by_id(path: Path) -> dict[str, Row]:
    if not path.exists():
        return {}
    rows = {}
    for row in read_jsonl(path):
        rows[row["id"]] = row
    return rows


def macro_f1_of(true_values: list[str], predicted_values: list[str]) -> float:
    classes = sorted(set(true_values) | set(predicted_values))
    return macro_f1(class_scores(true_values, predicted_values, classes))


def count_failures(model: str) -> int:
    """Every logged val failure counts, even if a re-run later fixed it: reliability matters."""
    fail_path = paths.LABELED / f"failures__{model.replace('/', '_')}.jsonl"
    if not fail_path.exists():
        return 0
    return sum(1 for failure in read_jsonl(fail_path) if failure["split"] == "val")


def build_pilot_report(out_file: Path = paths.DOC_REPORTS / "pilot.md") -> None:
    candidates = load_endpoint("teacher").candidates
    tickets = rows_by_id(paths.PROCESSED / "val.jsonl")

    runs: dict[str, dict[str, Row]] = {}
    for model in candidates:
        rows = rows_by_id(paths.LABELED / f"val__{model.replace('/', '_')}.jsonl")
        if rows:
            runs[model] = rows
    if not runs:
        raise UserError("No pilot files found in data/labeled/. Label some val tickets first.")

    # Compare on the tickets every candidate managed to label.
    common = sorted(set.intersection(*(set(rows) for rows in runs.values())))
    truth_cat = [tickets[i]["dataset_category"] for i in common]
    truth_pri = [tickets[i]["dataset_priority"] for i in common]

    lines = [
        "# Teacher pilot",
        "",
        "_Generated by `triage pilot-report`. Do not edit by hand; your verdict goes in_",
        "_docs/steps/03-teacher-labels.md and ADR-005._",
        "",
        f"Compared on **{len(common)}** val tickets labelled by every candidate.",
        "",
        "| model | labelled | failed calls | cat acc | cat macro-F1 | pri acc | pri macro-F1 "
        "| avg in tok | avg out tok | p50 latency s | est. cost for full set |",
        "|---" * 11 + "|",
    ]
    for model, rows in runs.items():
        cat = [rows[i]["label"]["category"] for i in common]
        pri = [rows[i]["label"]["priority"] for i in common]
        tokens_in = statistics.mean(r["input_tokens"] or 0 for r in rows.values())
        tokens_out = statistics.mean(r["output_tokens"] or 0 for r in rows.values())
        price = candidates[model]
        cost = N_FULL * (tokens_in * price.input + tokens_out * price.output) / 1e6
        cost_text = f"${cost:.2f}" if price.input or price.output else "set prices in models.yaml"
        median_latency = statistics.median(r["latency_s"] for r in rows.values())
        lines.append(
            f"| {model} | {len(rows)} | {count_failures(model)} "
            f"| {accuracy(truth_cat, cat):.2f} | {macro_f1_of(truth_cat, cat):.2f} "
            f"| {accuracy(truth_pri, pri):.2f} | {macro_f1_of(truth_pri, pri):.2f} "
            f"| {tokens_in:.0f} | {tokens_out:.0f} | {median_latency:.1f} | {cost_text} |"
        )

    if len(runs) > 1:
        lines += ["", "Agreement between candidates (same label on the same ticket):", ""]
        lines += ["| pair | category | priority |", "|---|---|---|"]
        for (name_a, a), (name_b, b) in itertools.combinations(runs.items(), 2):
            same_cat = sum(a[i]["label"]["category"] == b[i]["label"]["category"] for i in common)
            same_pri = sum(a[i]["label"]["priority"] == b[i]["label"]["priority"] for i in common)
            lines.append(f"| {name_a} vs {name_b} | {same_cat}/{len(common)} | {same_pri}/{len(common)} |")

    # Disagreements first: that is where the stronger model earns (or does not earn) its price.
    def disagreement(ticket_id: str) -> int:
        answers: set[Any] = set()
        for rows in runs.values():
            label = rows[ticket_id]["label"]
            answers.add((label["category"], label["priority"]))
        return len(answers)

    review = sorted(common, key=disagreement, reverse=True)[:N_REVIEW]
    lines += ["", f"## {len(review)} tickets to review by hand (disagreements first)", ""]
    for number, ticket_id in enumerate(review, 1):
        ticket = tickets[ticket_id]
        lines += [
            f"### {number}. `{ticket_id}`: dataset says {ticket['dataset_category']} / {ticket['dataset_priority']}",
            "",
            "> " + ticket["text"][:600].replace("\n", "\n> "),
            "",
        ]
        for model, rows in runs.items():
            label = rows[ticket_id]["label"]
            lines += [
                f"- **{model}**: {label['category']} / {label['priority']} / {label['sentiment']} "
                f"· products={json.dumps(label['products'])}",
                f"  - summary: {label['summary']}",
                f"  - reply: {label['suggested_reply']}",
            ]
        lines += ["- **Your call:** ", ""]

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text("\n".join(lines), encoding="utf-8")
    log.info("Wrote %s", out_file)
