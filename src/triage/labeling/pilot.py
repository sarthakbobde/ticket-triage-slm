"""Compare teacher candidates on the same val tickets -> docs/reports/pilot.md (ADR-005).

Agreement with the dataset's (noisy) labels is only a sanity check: ADR-010 explains why it is
low. The side-by-side tickets at the end are what a person actually judges on.
"""

import json
import logging
import statistics

from triage import paths
from triage.errors import UserError
from triage.evals.metrics import accuracy, class_scores, macro_f1
from triage.io import read_jsonl
from triage.settings import load_endpoint

log = logging.getLogger(__name__)

N_FULL = 3296  # tickets in test + val + train (docs/reports/splits.md)
N_REVIEW = 20  # how many tickets to list for a person to read


def rows_by_id(path):
    """Read a .jsonl file into a dictionary: ticket id -> row. Empty if the file does not exist."""
    rows = {}
    if not path.exists():
        return rows
    for row in read_jsonl(path):
        rows[row["id"]] = row
    return rows


def macro_f1_of(true_values, predicted_values):
    """Macro-F1 over every class that appears in either list."""
    seen = set()
    for value in true_values:
        seen.add(value)
    for value in predicted_values:
        seen.add(value)
    classes = sorted(seen)
    return macro_f1(class_scores(true_values, predicted_values, classes))


def count_failures(model):
    """How many val tickets failed for this model. Every logged failure counts, even if a re-run fixed it."""
    fail_path = paths.LABELED / f"failures__{model.replace('/', '_')}.jsonl"
    if not fail_path.exists():
        return 0
    count = 0
    for failure in read_jsonl(fail_path):
        if failure["split"] == "val":
            count = count + 1
    return count


def get_first(pair):
    """Used for sorting (number, ticket id) pairs by the number."""
    return pair[0]


def count_different_answers(ticket_id, runs):
    """How many different (category, priority) answers did the models give for this ticket?"""
    answers = set()
    for model in runs:
        label = runs[model][ticket_id]["label"]
        answers.add((label["category"], label["priority"]))
    return len(answers)


def build_pilot_report(out_file=None):
    if out_file is None:
        out_file = paths.DOC_REPORTS / "pilot.md"

    candidates = load_endpoint("teacher").candidates
    tickets = rows_by_id(paths.PROCESSED / "val.jsonl")

    # runs: model name -> its labelled rows (only models that have a file)
    runs = {}
    for model in candidates:
        rows = rows_by_id(paths.LABELED / f"val__{model.replace('/', '_')}.jsonl")
        if len(rows) > 0:
            runs[model] = rows
    if len(runs) == 0:
        raise UserError("No pilot files found in data/labeled/. Label some val tickets first.")

    # Compare only on the tickets that EVERY candidate managed to label.
    model_names = list(runs.keys())
    common = []
    for ticket_id in runs[model_names[0]]:
        in_all = True
        for model in model_names:
            if ticket_id not in runs[model]:
                in_all = False
        if in_all:
            common.append(ticket_id)
    common.sort()

    # What the dataset itself says for those tickets (a noisy yardstick, see ADR-010).
    truth_cat = []
    truth_pri = []
    for ticket_id in common:
        truth_cat.append(tickets[ticket_id]["dataset_category"])
        truth_pri.append(tickets[ticket_id]["dataset_priority"])

    lines = []
    lines.append("# Teacher pilot")
    lines.append("")
    lines.append("_Generated by `triage pilot-report`. Do not edit by hand; your verdict goes in_")
    lines.append("_docs/steps/03-teacher-labels.md and ADR-005._")
    lines.append("")
    lines.append(f"Compared on **{len(common)}** val tickets labelled by every candidate.")
    lines.append("")
    lines.append(
        "| model | labelled | failed calls | cat acc | cat macro-F1 | pri acc | pri macro-F1 "
        "| avg in tok | avg out tok | p50 latency s | est. cost for full set |"
    )
    lines.append("|---" * 11 + "|")

    for model in model_names:
        rows = runs[model]

        # What this model said for each common ticket.
        cat = []
        pri = []
        for ticket_id in common:
            cat.append(rows[ticket_id]["label"]["category"])
            pri.append(rows[ticket_id]["label"]["priority"])

        # Average tokens and the typical (median) time per ticket.
        input_tokens = []
        output_tokens = []
        latencies = []
        for row in rows.values():
            input_tokens.append(row["input_tokens"] or 0)
            output_tokens.append(row["output_tokens"] or 0)
            latencies.append(row["latency_s"])
        tokens_in = statistics.mean(input_tokens)
        tokens_out = statistics.mean(output_tokens)
        median_latency = statistics.median(latencies)

        # What labelling the full set would cost with this model.
        price = candidates[model]
        cost = N_FULL * (tokens_in * price.input + tokens_out * price.output) / 1e6
        if price.input or price.output:
            cost_text = f"${cost:.2f}"
        else:
            cost_text = "set prices in models.yaml"

        lines.append(
            f"| {model} | {len(rows)} | {count_failures(model)} "
            f"| {accuracy(truth_cat, cat):.2f} | {macro_f1_of(truth_cat, cat):.2f} "
            f"| {accuracy(truth_pri, pri):.2f} | {macro_f1_of(truth_pri, pri):.2f} "
            f"| {tokens_in:.0f} | {tokens_out:.0f} | {median_latency:.1f} | {cost_text} |"
        )

    # If there are several candidates, show how often each pair agrees.
    if len(model_names) > 1:
        lines.append("")
        lines.append("Agreement between candidates (same label on the same ticket):")
        lines.append("")
        lines.append("| pair | category | priority |")
        lines.append("|---|---|---|")
        for first in range(len(model_names)):
            for second in range(first + 1, len(model_names)):
                name_a = model_names[first]
                name_b = model_names[second]
                same_cat = 0
                same_pri = 0
                for ticket_id in common:
                    label_a = runs[name_a][ticket_id]["label"]
                    label_b = runs[name_b][ticket_id]["label"]
                    if label_a["category"] == label_b["category"]:
                        same_cat = same_cat + 1
                    if label_a["priority"] == label_b["priority"]:
                        same_pri = same_pri + 1
                lines.append(f"| {name_a} vs {name_b} | {same_cat}/{len(common)} | {same_pri}/{len(common)} |")

    # Put the tickets the models disagree on first: that is where a stronger model earns (or does
    # not earn) its price. A stable sort keeps tickets with the same number in their original order.
    scored = []
    for ticket_id in common:
        scored.append((count_different_answers(ticket_id, runs), ticket_id))
    scored.sort(key=get_first, reverse=True)
    review = []
    for number, ticket_id in scored[:N_REVIEW]:
        review.append(ticket_id)

    lines.append("")
    lines.append(f"## {len(review)} tickets to review by hand (disagreements first)")
    lines.append("")
    position = 0
    for ticket_id in review:
        position = position + 1
        ticket = tickets[ticket_id]
        lines.append(
            f"### {position}. `{ticket_id}`: dataset says {ticket['dataset_category']} / {ticket['dataset_priority']}"
        )
        lines.append("")
        lines.append("> " + ticket["text"][:600].replace("\n", "\n> "))
        lines.append("")
        for model in model_names:
            label = runs[model][ticket_id]["label"]
            lines.append(
                f"- **{model}**: {label['category']} / {label['priority']} / {label['sentiment']} "
                f"· products={json.dumps(label['products'])}"
            )
            lines.append(f"  - summary: {label['summary']}")
            lines.append(f"  - reply: {label['suggested_reply']}")
        lines.append("- **Your call:** ")
        lines.append("")

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text("\n".join(lines), encoding="utf-8")
    log.info("Wrote %s", out_file)
