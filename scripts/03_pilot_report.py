"""Step 03: compare the pilot candidates -> docs/reports/pilot.md (ADR-005).

Run after labelling the same 50 val tickets with each candidate:
  uv run python scripts/03_pilot_report.py

Agreement with the dataset's (noisy) labels is only a sanity check: ~0.6-0.7 is expected
(ADR-010). The 20 side-by-side tickets at the end are what you actually judge on.
"""

import json
import statistics
import sys
from pathlib import Path

import yaml
from sklearn.metrics import accuracy_score, f1_score

sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parents[1]
LABELED = ROOT / "data" / "labeled"
OUT_REPORT = ROOT / "docs" / "reports" / "pilot.md"
N_FULL = 3296  # tickets in test + val + train (docs/reports/splits.md)
N_REVIEW = 20


def load_jsonl(path: Path) -> dict[str, dict]:
    return {r["id"]: r for r in map(json.loads, path.open(encoding="utf-8"))} if path.exists() else {}


def main() -> None:
    candidates = yaml.safe_load((ROOT / "configs" / "models.yaml").read_text(encoding="utf-8"))[
        "teacher"
    ]["candidates"]
    tickets = load_jsonl(ROOT / "data" / "processed" / "val.jsonl")
    runs = {m: load_jsonl(LABELED / f"val__{m.replace('/', '_')}.jsonl") for m in candidates}
    runs = {m: r for m, r in runs.items() if r}
    if not runs:
        sys.exit("No pilot files found in data/labeled/. Run 03_label_with_teacher.py first.")

    # Compare on the tickets every candidate managed to label.
    common = sorted(set.intersection(*(set(r) for r in runs.values())))
    truth_cat = [tickets[i]["dataset_category"] for i in common]
    truth_pri = [tickets[i]["dataset_priority"] for i in common]

    lines = [
        "# Teacher pilot",
        "",
        "_Generated by `scripts/03_pilot_report.py`. Do not edit by hand; your verdict goes in_",
        "_docs/steps/03-teacher-labels.md and ADR-005._",
        "",
        f"Compared on **{len(common)}** val tickets labelled by every candidate.",
        "",
        "| model | labelled | failed calls | cat acc | cat macro-F1 | pri acc | pri macro-F1 "
        "| avg in tok | avg out tok | p50 latency s | est. cost for full set |",
        "|---" * 11 + "|",
    ]
    for m, r in runs.items():
        # Every logged failure counts, even if a re-run later fixed it: reliability matters.
        fail_path = LABELED / f"failures__{m.replace('/', '_')}.jsonl"
        fails = [json.loads(x) for x in fail_path.open(encoding="utf-8")] if fail_path.exists() else []
        n_fail = sum(1 for f in fails if f["split"] == "val")
        cat = [r[i]["label"]["category"] for i in common]
        pri = [r[i]["label"]["priority"] for i in common]
        tin = statistics.mean(x["input_tokens"] or 0 for x in r.values())
        tout = statistics.mean(x["output_tokens"] or 0 for x in r.values())
        price = candidates[m]
        cost = N_FULL * (tin * price["input"] + tout * price["output"]) / 1e6
        cost_s = f"${cost:.2f}" if price["input"] or price["output"] else "set prices in models.yaml"
        lines.append(
            f"| {m} | {len(r)} | {n_fail} "
            f"| {accuracy_score(truth_cat, cat):.2f} | {f1_score(truth_cat, cat, average='macro'):.2f} "
            f"| {accuracy_score(truth_pri, pri):.2f} | {f1_score(truth_pri, pri, average='macro'):.2f} "
            f"| {tin:.0f} | {tout:.0f} | {statistics.median(x['latency_s'] for x in r.values()):.1f} "
            f"| {cost_s} |"
        )

    names = list(runs)
    if len(names) == 2:
        a, b = (runs[n] for n in names)
        agree_cat = sum(a[i]["label"]["category"] == b[i]["label"]["category"] for i in common)
        agree_pri = sum(a[i]["label"]["priority"] == b[i]["label"]["priority"] for i in common)
        lines += [
            "",
            f"Candidates agree with each other on category for **{agree_cat}/{len(common)}** and "
            f"priority for **{agree_pri}/{len(common)}** tickets.",
        ]

    # Disagreements first: that's where the stronger model earns (or doesn't earn) its price.
    def disagreement(i: str) -> int:
        return len({(r[i]["label"]["category"], r[i]["label"]["priority"]) for r in runs.values()})

    review = sorted(common, key=disagreement, reverse=True)[:N_REVIEW]
    lines += ["", f"## {len(review)} tickets to review by hand (disagreements first)", ""]
    for n, i in enumerate(review, 1):
        t = tickets[i]
        lines += [
            f"### {n}. `{i}`: dataset says {t['dataset_category']} / {t['dataset_priority']}",
            "",
            "> " + t["text"][:600].replace("\n", "\n> "),
            "",
        ]
        for m, r in runs.items():
            lab = r[i]["label"]
            lines += [
                f"- **{m}**: {lab['category']} / {lab['priority']} / {lab['sentiment']} "
                f"· products={lab['products']}",
                f"  - summary: {lab['summary']}",
                f"  - reply: {lab['suggested_reply']}",
            ]
        lines += ["- **Your call:** ", ""]

    OUT_REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
